//Área do Trapézio


alert("Área do Trapézio")
var basemenor = parseFloat(prompt("Digite o número da base menor do seu Trapézio: "))
var basemaior = parseFloat(prompt("Digite o número da base maior do seu Trapézio: "))
var altura = parseFloat(prompt("Digite o número da altura do seu Trapézio: "))
var area = ((basemenor + basemaior)*altura)/2
alert("A área do seu trapézio é: " + area + "cm²")
