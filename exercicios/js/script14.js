//Perímetro do Retângulo


alert("Área do Retângulo")
var base = parseFloat(prompt("Digite o número da medida da base do seu Retângulo: "))
var altura = parseFloat(prompt("Digite o número da medida da altura do seu Retângulo: "))
var perimetro =  (base + altura ) * 2
alert("O valor do Perímetro do Retângulo é: " + perimetro + "cm")
